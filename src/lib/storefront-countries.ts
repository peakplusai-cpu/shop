const COUNTRY_NAME_BY_CODE = new Map<string, string>(
  STOREFRONT_COUNTRIES.map((country) => [country.code, country.name]),
);

export function countryNameForCode(code: string): string | null {
  return COUNTRY_NAME_BY_CODE.get(code.trim().toUpperCase()) ?? null;
}

export function officialCountryName(
  countryCode: string,
  fallback = '',
): string {
  return countryNameForCode(countryCode) ?? fallback;
}
